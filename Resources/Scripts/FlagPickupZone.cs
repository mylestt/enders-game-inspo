using Godot;
using System;

public partial class FlagPickupZone : Area3D
{
    #region========================================( Variables)======================================================//
    /*-----[ Inspector Variables ]------------------------------------------------------------------------------------*/


    /*-----[ External Variables ]-------------------------------------------------------------------------------------*/
    [Signal]
    public delegate void FlagPickedUpEventHandler(Node3D player);
	

    /*-----[ Internal Variables ]-------------------------------------------------------------------------------------*/


    /*-----[ Reference Variables ]------------------------------------------------------------------------------------*/


    #endregion


    #region=======================================( Functions )======================================================= //
    /*-----[ Mono Functions ]-----------------------------------------------------------------------------------------*/
    public override void _Ready()
    {
        BodyEntered += OnBodyEntered;
    }

    public override void _Process(double delta)
    {
    }

    /*-----[ Internal Functions ]-------------------------------------------------------------------------------------*/
    private void OnBodyEntered(Node3D body)
    {
        if (!body.HasMethod("get_peer_id"))
            return;

        EmitSignal(SignalName.FlagPickedUp, body);
    }


    /*-----[ External Functions ]-------------------------------------------------------------------------------------*/


    #endregion
}